# Compiles the GPU shaders in shaders\ to SPIR-V and writes each as a C++ header of 32-bit words in
# src\core\shaders\, so the project builds without the Vulkan SDK. Run after changing a shader:
#   .\tools\compile_shaders.ps1
# Needs glslc from the Vulkan SDK (https://vulkan.lunarg.com).
$root = Split-Path $PSScriptRoot -Parent
$sdk = $env:VULKAN_SDK
if (-not $sdk) { $sdk = [Environment]::GetEnvironmentVariable('VULKAN_SDK', 'Machine') }
if (-not $sdk) { $sdk = (Get-ChildItem C:\VulkanSDK -Directory -ErrorAction SilentlyContinue | Sort-Object Name | Select-Object -Last 1).FullName }
$glslc = Join-Path $sdk 'Bin\glslc.exe'
if (-not (Test-Path $glslc)) { Write-Error "glslc not found; install the Vulkan SDK."; exit 1 }

$out = Join-Path $root 'src\core\shaders'
New-Item -ItemType Directory -Force $out | Out-Null
foreach ($shader in Get-ChildItem (Join-Path $root 'shaders') -Filter *.comp) {
    $spirv = Join-Path $env:TEMP "$($shader.BaseName).spv"
    & $glslc -O --target-env=vulkan1.1 -o $spirv $shader.FullName
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    $bytes = [System.IO.File]::ReadAllBytes($spirv)
    $words = for ($i = 0; $i -lt $bytes.Length; $i += 4) { '0x{0:x8}u' -f [BitConverter]::ToUInt32($bytes, $i) }
    $name = ($shader.BaseName.ToUpper()) + '_SPIRV'
    $lines = @("// Generated by tools\compile_shaders.ps1 from shaders\$($shader.Name); do not edit.",
               '#pragma once', '#include <cstdint>', '', "inline constexpr std::uint32_t $name[] = {")
    for ($i = 0; $i -lt $words.Count; $i += 8) { $lines += '    ' + (($words[$i..([Math]::Min($i + 7, $words.Count - 1))]) -join ', ') + ',' }
    $lines += '};'
    Set-Content -Encoding ascii (Join-Path $out "$($shader.BaseName).spv.h") ($lines -join "`n")
    Write-Host "compiled $($shader.Name)"
}
